const slugify = (s: string) => s.toLowerCase().replace(/[^a-z]+/g, "-");

function card(ctx: Ctx, p: Project, large: boolean) {
  const cover = p.shots[0].file;
  const a = asset(cover);
  const sizes = large ? "(min-width: 48rem) 50vw, 100vw" : "(min-width: 64rem) 33vw, (min-width: 48rem) 50vw, 100vw";
  const img = `<img src="${src(ctx, cover, !large)}" srcset="${src(ctx, cover, true)} 800w, ${src(ctx, cover)} ${a.w}w" sizes="${sizes}" alt="" loading="lazy" decoding="async">`;
  const hover = a.video ? `<video muted loop playsinline preload="none" data-hover src="${ctx.base}media/${cover}.mp4"></video>` : "";
  return `<li data-kinds="${p.kinds.join(" ")}" data-fade><a class="card" href="${href(ctx, `work/${p.slug}/`)}">
  <div class="card-media" style="view-transition-name:cover-${p.slug}">${img}${hover}</div>
  <p class="card-top"><span class="card-name">${esc(p.name)}</span><span class="card-year">${p.year}</span></p>
  <p class="card-head">${esc(p.headline)}</p>
  <p class="card-tags"><span class="status" data-ev="${slugify(p.evidence)}">${p.evidence}</span><span>${esc(p.role.slice(0, 2).join(", "))}</span></p>
</a></li>`;
}

